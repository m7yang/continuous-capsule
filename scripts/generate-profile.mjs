// Expand the frozen native-render fit into the existing height-scaled profile.
import { readFileSync, writeFileSync } from 'node:fs';

const { quarter } = JSON.parse(readFileSync(
  new URL('../tests/fixtures/capsule-fit-profile.json', import.meta.url), 'utf8',
));
const width = 2, height = 1, continuous = [];
for (const [right, bottom, reverse] of [[false, false, false], [true, false, true], [true, true, false], [false, true, true]]) {
  const map = ([x, y]) => [right ? width - x : x, bottom ? height - y : y];
  const segments = reverse ? quarter.toReversed().map(segment => segment.toReversed()) : quarter;
  continuous.push({ type: continuous.length ? 'L' : 'M', points: map(segments[0][0]) });
  for (const [a, b, c, d] of segments) {
    // Exact de Casteljau subdivision avoids a CSS/SVG rasterization discrepancy
    // at fractional 3× positions. Bake it here; no runtime subdivision or refit.
    const mid = (p, q) => p.map((value, i) => (value + q[i]) / 2);
    const ab = mid(a, b), bc = mid(b, c), cd = mid(c, d);
    const abc = mid(ab, bc), bcd = mid(bc, cd), center = mid(abc, bcd);
    continuous.push({ type: 'C', points: [ab, abc, center].flatMap(map) });
    continuous.push({ type: 'C', points: [bcd, cd, d].flatMap(map) });
  }
}
continuous.push({ type: 'Z', points: [] });
writeFileSync(new URL('../src/profile.js', import.meta.url),
  '// Generated by scripts/generate-profile.mjs from the frozen raster fit.\n' +
  '// SwiftUI macOS 27.0 (26A428), 332×150 at 16×; see docs/research.md.\n' +
  `export const profile = ${JSON.stringify({ width, height, continuous }, null, 2)};\n`,
);

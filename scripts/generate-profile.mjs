// Derive the small browser payload from the retained native fixture.
import { readFileSync, writeFileSync } from 'node:fs';

const fixture = JSON.parse(
  readFileSync(new URL('../tests/fixtures/apple-capsules.json', import.meta.url), 'utf8'),
);
const { width, height, continuous } = fixture.samples[0];
const profile = { width, height, continuous };
writeFileSync(
  new URL('../src/profile.js', import.meta.url),
  `// Generated by scripts/generate-profile.mjs from the retained native fixture.\n` +
    `// ${fixture.source}; ${fixture.os}\n` +
    `export const profile = ${JSON.stringify(profile, null, 2)};\n`,
);
